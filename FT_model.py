# Common imports
import numpy as np
import matplotlib.pyplot as plt

# ------------------------------------------------------------
# HHLS (Hodgkin-Huxley low-sodium) model parameters
# Units: V in mV, t in ms, conductances in mS/cm^2,
#        capacitance in uF/cm^2, current density in uA/cm^2
# ------------------------------------------------------------

C_m = 1.0        # membrane capacitance (uF/cm^2)

E_Na = 50        # sodium reversal potential (mV)
E_K = -77        # potassium reversal potential (mV)
E_L = -54.387    # leak reversal potential (mV)

gbar_Na = 41.0   # maximum sodium conductance (mS/cm^2)    [standard HH: 120]
gbar_K = 79.0    # maximum potassium conductance (mS/cm^2) [standard HH: 36]
g_L = 0.3        # leak conductance (mS/cm^2)

A = 1e-6         # membrane area: 100 um^2 = 1e-6 cm^2

dt = 0.01        # time-step for integration (ms)

V0 = -67.80      # V initial condition (HHLS resting potential, mV)
m0 = 0.0379      # m initial condition (m_inf at V0)
h0 = 0.6895      # h initial condition (h_inf at V0)
n0 = 0.2758      # n initial condition (n_inf at V0)


# ------------------------------------------------------------
# Voltage-dependent rate functions
# ------------------------------------------------------------

def alpha_m(V):
    """Return alpha_m(V)."""
    return (0.1*(V + 40)) / (1 - np.exp(-0.1*(V + 40)))

def beta_m(V):
    """Return beta_m(V)."""
    return 4*np.exp(-0.0556*(V + 65))

def alpha_h(V):
    """Return alpha_h(V)."""
    return 0.07*np.exp(-0.05*(V + 65))

def beta_h(V):
    """Return beta_h(V)."""
    return 1 / (1 + np.exp(-0.1*(V + 35)))

def alpha_n(V):
    """Return alpha_n(V)."""
    return (0.01*(V + 55)) / (1 - np.exp(-0.1*(V + 55)))

def beta_n(V):
    """Return beta_n(V)."""
    return 0.125*np.exp(-0.0125*(V + 65))

# ------------------------------------------------------------
# One Euler step of the full Hodgkin-Huxley model
# ------------------------------------------------------------

def hh_euler_step(V, m, h, n, I_ext, dt):
    """
    Advance the full Hodgkin-Huxley model by one Euler step.

    Parameters
    ----------
    V : Membrane voltage.
    m, h, n : Hodgkin-Huxley gating variables.
    I_ext : External current density.
    dt : Integration step.

    Returns
    -------
    V_new, m_new, h_new, n_new
    """

    # Compute sodium, potassium, and leak currents.
    I_Na = gbar_Na * (m**3) * h *(V - E_Na)
    I_K = gbar_K * n**4 * (V - E_K)
    I_L = g_L*(V - E_L)

    I_m = I_L + I_K + I_Na

    # Compute dV/dt.
    dVdt = (-1 * I_m + I_ext) / C_m # I_e corresponds to I_e / A in the equations

    # Compute dm/dt, dh/dt, dn/dt.
    dmdt = alpha_m(V) * (1 - m) - beta_m(V) * m
    dhdt = alpha_h(V) * (1 - h) - beta_h(V) * h
    dndt = alpha_n(V) * (1 - n) - beta_n(V) * n

    # Euler updates.
    V_new = V + dt * dVdt
    m_new = m + dt * dmdt
    h_new = h + dt * dhdt
    n_new = n + dt * dndt

    return V_new, m_new, h_new, n_new

# ------------------------------------------------------------
# General simulation function
# ------------------------------------------------------------

def simulate_hh(I_ext, T, dt, V_init, m_init, h_init, n_init):
    """
    Simulate the HH model.

    I_ext may be:
      - a scalar constant current, or
      - an array with one value per time point.
    """

    t = np.arange(0, T + dt, dt)

    V = np.zeros_like(t)
    m = np.zeros_like(t)
    h = np.zeros_like(t)
    n = np.zeros_like(t)

    V[0], m[0], h[0], n[0] = V_init, m_init, h_init, n_init

    # Convert scalar current to an array if necessary.
    I_ext = np.atleast_1d(I_ext)
    if len(I_ext) == 1:
      I_ext = I_ext[0] * np.ones(len(t))

    # Step through time with hh_euler_step(...).
    for i in range(len(t) - 1):
      V[i+1], m[i+1], h[i+1], n[i+1] = hh_euler_step(V[i], m[i], h[i], n[i], I_ext[i], dt)

    return t, V, m, h, n

